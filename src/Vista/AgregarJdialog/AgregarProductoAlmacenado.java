    private void BtnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnAgregarActionPerformed
        String nombreAlmacen = (String) jComboNombreAlmacen.getSelectedItem();
        String nombreCultivo = (String) jComboNombreCultivo.getSelectedItem();
        String cantidadStr = jTextField2.getText().trim();
        String fechaIngreso = jTextField3.getText().trim(); 

        // Validaciones básicas
        if (nombreAlmacen == null || nombreAlmacen.isEmpty() ||
            nombreCultivo == null || nombreCultivo.isEmpty() ||
            cantidadStr.isEmpty() || fechaIngreso.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe completar todos los campos obligatorios.", "Validación", JOptionPane.WARNING_MESSAGE);
            return;
        }

        double cantidadKg;
        try {
            cantidadKg = Double.parseDouble(cantidadStr);
            if (cantidadKg <= 0) {
                JOptionPane.showMessageDialog(this, "La cantidad debe ser un número positivo.", "Validación", JOptionPane.ERROR_MESSAGE);
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Error de formato: La cantidad debe ser un número válido.", "Validación", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validar formato de fecha yyyy-MM-dd
        try {
            LocalDate.parse(fechaIngreso, fechaFormatter);
        } catch (DateTimeParseException e) {
            JOptionPane.showMessageDialog(this, "La fecha de ingreso debe tener el formato YYYY-MM-DD.", "Validación", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Mapear nombres a IDs de forma segura
        int idAlmacen = mapaAlmacenes.getOrDefault(nombreAlmacen, -1);
        int idCultivo = mapaCultivos.getOrDefault(nombreCultivo, -1);

        if (idAlmacen == -1) {
            JOptionPane.showMessageDialog(this, "No se encontró el almacén seleccionado.", "Error Interno", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (idCultivo == -1) {
            JOptionPane.showMessageDialog(this, "No se encontró el cultivo seleccionado.", "Error Interno", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Crear DTO y llamar al controlador
        try {
            ProductoAlmacenadoDTO productoDTO = new ProductoAlmacenadoDTO(
                0, 
                idAlmacen, 
                idCultivo, 
                nombreCultivo,
                cantidadKg, 
                fechaIngreso, 
                null 
            );

            if (controladorBase.guardarProductoAlmacenado(productoDTO)) {
                JOptionPane.showMessageDialog(this, "Producto almacenado guardado con éxito.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                ObservadorManager.getInstancia().notificarCambio("PRODUCTOALMACENADO"); 
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(this, "Error: No se pudo guardar el producto almacenado (Validación de BD).", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error inesperado: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }//GEN-LAST:event_BtnAgregarActionPerformed

