    private void cargarCombos() {
        // Vaciar controles antes de llenar
        jComboNombreAlmacen.removeAllItems();
        jComboNombreCultivo.removeAllItems();
        mapaAlmacenes.clear();
        mapaCultivos.clear();
        
        try {
            // Obtener almacenes desde el controlador (usa AlmacenamientoService)
            List<AlmacenamientoDTO> almacenes = controladorBase.obtenerDatosAlmacenes();
            if (almacenes != null) {
                for (AlmacenamientoDTO a : almacenes) {
                    if (a != null && a.getNombre() != null) {
                        mapaAlmacenes.put(a.getNombre(), a.getIdAlmacen());
                        jComboNombreAlmacen.addItem(a.getNombre());
                    }
                }
            }
        } catch (Exception e) {
            System.err.println("Error cargando almacenes en AgregarProductoAlmacenado: " + e.getMessage());
        }
        
        try {
            // Obtener cultivos desde el controlador (usa CultivoService)
            List<CultivoDTO> cultivos = controladorBase.obtenerTodosLosCultivos();
            if (cultivos != null) {
                for (CultivoDTO c : cultivos) {
                    if (c != null && c.getNombre() != null) {
                        mapaCultivos.put(c.getNombre(), c.getId());
                        jComboNombreCultivo.addItem(c.getNombre());
                    }
                }
            }
        } catch (Exception e) {
            System.err.println("Error cargando cultivos en AgregarProductoAlmacenado: " + e.getMessage());
        }
    }
